const char *cxidv_telem_name(uint32_t item)
{
	return item < CXIDV_TELEM_COUNT ? telem_names[item] : NULL;
}

int cxidv_telem_lookup(const char *name)
{
	uint32_t i;

	if (!name)
		return -1;
	for (i = 0; i < CXIDV_TELEM_COUNT; i++)
		if (!strcmp(telem_names[i], name))
			return i;
	return -1;
}

int cxidv_telem_get_set(enum cxidv_telem_set set, const uint64_t **items, uint32_t *count)
{
	if ((unsigned int)set >= CXIDV_TELEM_SET_COUNT || !items || !count)
		return EINVAL;
	*items = telem_sets[set].items;
	*count = telem_sets[set].count;
	return 0;
}
